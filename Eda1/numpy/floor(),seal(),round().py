import numpy as np

#FLOOOR()------------------------------------------------------

a=np.array([[4.1,5.2,6.45,1.56],[1.43,2.7,3.8,4.8],[6.3,7.5,8.2,3.4],[7.1,6.5,5.9,4.1],[1.1,3.3,5.3,7.5]])
b=np.floor(a)

print(b)
print('*'*100)


#   2.1 ===> 2.
#   5.9 ===> 5.



#ceil()----------------------------------------------------------


a=np.array([[4.1,5.2,6.45,1.56],[1.43,2.7,3.8,4.8],[6.3,7.5,8.2,3.4],[7.1,6.5,5.9,4.1],[1.1,3.3,5.3,7.5]])
b=np.ceil(a)

print(b)
print('*'*100)

#   4.3 ===> 5
#   1.1 ====> 2